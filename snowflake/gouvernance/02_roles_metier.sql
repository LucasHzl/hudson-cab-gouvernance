GRANT SELECT ON ALL TABLES IN SCHEMA NYC_TAXI.MARTS TO ROLE ANALYSTE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA NYC_TAXI.MARTS TO ROLE ANALYSTE;
